/**
 * 替换净化：读正文时按规则改写文本（#28）。
 *
 * 字段名照 legado 的 `replaceRule`，导出的文件两种应用能互相读。
 * 只实现「正则替换 / 字面替换」这一层，不做 legado 的那套正则 DSL ——
